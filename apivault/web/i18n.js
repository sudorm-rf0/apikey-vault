let currentLang = localStorage.getItem("apivault_lang") || "en";

function t(key) {
  const table = I18N[currentLang] || I18N.en;
  return table[key] !== undefined ? table[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
}

function tf(key, vars) {
  let s = t(key);
  for (const [k, v] of Object.entries(vars || {})) {
    s = s.split("{" + k + "}").join(String(v));
  }
  return s;
}

function setLang(lang) {
  currentLang = lang === "zh" ? "zh" : "en";
  localStorage.setItem("apivault_lang", currentLang);
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  applyI18n();
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  const langSel = document.getElementById("settings-lang");
  if (langSel) langSel.value = currentLang;
}
